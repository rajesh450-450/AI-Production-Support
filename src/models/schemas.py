from typing import Literal

from pydantic import BaseModel


class PlanStep(BaseModel):
    """
    Represents one executable investigation step.

    The Planner creates investigation steps only.
    Final answer generation is handled separately by AnswerAgent.
    """

    step: int

    type: Literal[
        "analysis",
        "tool",
        "review",
    ]

    description: str

    tool: str | None = None


class InvestigationPlan(BaseModel):
    """
    Complete investigation plan generated by the Planner.
    """

    steps: list[PlanStep]


class ReviewDecision(BaseModel):
    """
    Output produced by the Reviewer.
    """

    status: Literal[
        "success",
        "retry",
    ]

    reason: str


class FinalAnswer(BaseModel):
    """
    Final response returned to the user.
    """

    answer: str

    confidence: Literal[
        "high",
        "medium",
        "low",
    ]