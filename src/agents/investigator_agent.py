from src.memory.execution_context import execution_context

from src.services.execution_service import ExecutionService


execution_service = ExecutionService()


def executor_node(state):
    """
    Execute the complete investigation plan generated by Planner.

    All steps in the current plan are executed sequentially.

    Evidence is accumulated in AgentState and preserved for
    future planning iterations.
    """

    print("\n" + "=" * 80)
    print("ENTERING EXECUTOR")
    print("=" * 80)

    execution_context.add_event(
        "INFO",
        "Executor",
        "Executor started.",
    )

    total_steps = len(state["plan"])

    if total_steps == 0:
        execution_context.add_event(
            "WARNING",
            "Executor",
            "Planner returned an empty investigation plan.",
        )

        print("\nNo investigation steps were provided.")

        return state

    for step in state["plan"]:

        execution_context.update_progress(
            current_phase="Execution",
            current_step=step.step,
            total_steps=total_steps,
            current_tool=step.tool or "",
        )

        print("\n" + "=" * 70)
        print(
            f"STEP {step.step}/{total_steps}"
        )
        print("=" * 70)

        print(
            f"Type        : {step.type}"
        )

        print(
            f"Description : {step.description}"
        )

        print(
            f"Tool        : "
            f"{step.tool if step.tool else 'None'}"
        )

        state = execution_service.execute(
            state=state,
            step=step,
        )

        execution_context.add_event(
            "INFO",
            "Executor",
            (
                f"Completed investigation "
                f"step {step.step}."
            ),
        )

    print("\nLeaving Executor")

    execution_context.add_event(
        "INFO",
        "Executor",
        "Executor completed.",
    )

    return state